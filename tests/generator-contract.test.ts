import { describe, expect, it, vi } from 'vitest';
import type { AudioProvider } from '../src/services/providers/provider-interface.js';
import { ElevenLabsGeneratorAdapter } from '../src/services/generators/elevenlabs-adapter.js';
import { GeneratorRegistry } from '../src/services/generators/registry.js';
import type { AssetGenerator, GenerationRequest } from '../src/services/generators/types.js';

function makeAudioProvider(): AudioProvider {
  return {
    generateDialogue: vi.fn(),
    generateMusic: vi.fn(),
    generateSFX: vi.fn(),
    getQuota: vi.fn(),
    getVoices: vi.fn(),
  };
}

describe('provider-neutral generator contract', () => {
  it('adapts synchronous ElevenLabs dialogue into a completed operation and generated bytes', async () => {
    const audioProvider = makeAudioProvider();
    const generatedBytes = Buffer.from('audio-candidate');
    vi.mocked(audioProvider.generateDialogue).mockResolvedValue(generatedBytes);
    const adapter = new ElevenLabsGeneratorAdapter(audioProvider);

    const request: GenerationRequest = {
      id: 'take-001',
      assetKind: 'dialogue',
      prompt: 'Hold the line.',
      settings: {
        voiceId: 'voice-001',
        voice: { stability: 0.4, similarity_boost: 0.8 },
        modelId: 'eleven_v3',
      },
    };
    const operation = await adapter.submit(request);

    expect(operation).toMatchObject({
      providerId: 'elevenlabs', operationId: 'elevenlabs:take-001', requestId: 'take-001', status: 'completed',
    });
    expect(await adapter.poll(operation)).toEqual(operation);
    expect(audioProvider.generateDialogue).toHaveBeenCalledWith(
      'Hold the line.', 'voice-001', { stability: 0.4, similarity_boost: 0.8 }, 'eleven_v3',
    );
    await expect(adapter.download(operation)).resolves.toMatchObject({
      bytes: generatedBytes,
      mimeType: 'audio/mpeg',
      providerMetadata: { provider: 'elevenlabs', assetKind: 'dialogue', requestId: 'take-001' },
    });
  });

  it('rejects unsupported media before an audio provider is called', async () => {
    const audioProvider = makeAudioProvider();
    const adapter = new ElevenLabsGeneratorAdapter(audioProvider);

    await expect(adapter.submit({ id: 'image-001', assetKind: 'image', prompt: 'A transparent goblin.' }))
      .rejects.toThrow('elevenlabs does not support image generation');
    expect(audioProvider.generateDialogue).not.toHaveBeenCalled();
    expect(adapter.capabilities()).toMatchObject({
      media: { dialogue: {}, music: {}, sfx: {} },
      voices: true,
      quota: true,
    });
  });

  it('registers injected generators by capability without making network calls', () => {
    const fakeVideoGenerator: AssetGenerator = {
      providerId: 'fake-video',
      capabilities: () => ({ providerId: 'fake-video', media: { video: { aspectRatios: ['16:9', '9:16'] } } }),
      submit: vi.fn(),
      poll: vi.fn(),
      download: vi.fn(),
    };
    const registry = new GeneratorRegistry([fakeVideoGenerator]);

    expect(registry.supports('fake-video', 'video')).toBe(true);
    expect(registry.supports('fake-video', 'image')).toBe(false);
    expect(registry.get('fake-video')).toBe(fakeVideoGenerator);
  });
});
